#!/usr/bin/env python3
"""Turn WINDEV's project technical documentation (the "dossier" PDF) into per-element JSON.

The dossier is generated by WINDEV from the project and states what the text sources keep
encrypted: window titles and properties, each control's caption, tab order, input mask and
size, button type and images, every query's SQL, parameters and conditions, and the analysis
item types. Requires `pip install pypdf`. Parsing works on page text, so it is testable without
PDFs; the raw section text is always kept next to the parsed fields.
"""
import argparse
import collections
import json
from pathlib import Path
import re
import sys

# Properties whose names start with a FIELDS key but mean something else.
LONGER = ('Image handling menu', 'Caption + Time left', 'Tab order (input)', 'Input mask (display)', 'Title angle')
HEADER = re.compile(r'^Part (\d+)\s+(.*)$')
DETAIL = re.compile(r'^(Button|Edit control|Caption|Image|Supercontrol|Table|Column|Combo box|List box|Check box|'
                    r'Radio button|Tab|Static|Progress bar|Looper|Internal window|Layout|Spin|Slider|Scrollbar|'
                    r'Rating|Calendar|Chart|Toolbar|Menu option|Cell|Tree view|Rich text|HTML|Zone|Sidebar|'
                    r'Organizer|Scheduler|Shape|Splitter|[A-Z][A-Za-z]+(?: [A-Za-z]+)*) : ([A-Za-z_][\w$]*(?:\.[A-Za-z_][\w$]*)*)'
                    r'(?: \((\d+)\))?$')  # table columns carry their position: "Table column : TABLE_X.COL_Y (1)"
# Control table rows: "EDT_Codigo 14 31 158 25 0 Active Numeric" (windows, pixels) or
# "STC_Codigo Caption 0.00 0.00 6.09 14.66 0.10 Solid TBL-" (reports, millimetres).
COLUMN_ROW = re.compile(r'^(\d+) (Active|Read-only|Read-onl|Grayed|Inactive) (Left|Right|Center|Justified) '
                        r'(Top|Center|Bottom) (.+)$')
WINDOW_ROW = re.compile(r'^([A-Za-z_][\w$]*) (-?\d+) (-?\d+) (\d+) (\d+) (\d+)(?: (.*))?$')
REPORT_ROW = re.compile(r'^([A-Za-z_][\w$]*) ([A-Z][a-z]+(?: [a-z]+)*) (-?\d+\.\d+) (-?\d+\.\d+) (\d+\.\d+) (\d+\.\d+)(?: (.*))?$')
STATES = ('Active', 'Read-only', 'Read-onl', 'Grayed', 'Inactive')
BUTTON_TYPES = ('Normal', 'Validate', 'Abort', 'Cancel', 'Help', 'Interrupt')
INPUT_TYPES = ('Text', 'Numeric', 'Date', 'Time', 'Currency', 'Duration', 'Date and Time', 'Password')
FIELDS = {'Caption': 'caption', 'Tab order': 'tab_order', 'Input mask': 'input_mask', 'Input size': 'input_size',
          'Image': 'image', 'Background image': 'background_image', 'Initial value': 'initial_value',
          'Anchoring': 'anchoring', 'Title': 'title', 'Linked item': 'linked_item', 'File link': 'linked_item',
          'Input type': 'input_type', 'Button type': 'button_type', 'Data binding': 'linked_item',
          'Browsed file': 'browsed_file', 'Browsed item': 'browsed_item', 'Stored item': 'stored_item',
          'Displayed item': 'displayed_item', 'Display mask': 'display_mask'}


def drawn_images(page):
    """Images painted by this page's content stream. `page.images` lists the whole shared resource
    dictionary (about 150 images on every dossier page), so it cannot be used directly."""
    contents = page.get_contents()
    painted = set(re.findall(rb'/([A-Za-z0-9_.-]+)\s+Do\b', contents.get_data() if contents is not None else b''))
    return [image for image in page.images if image.name.rsplit('.', 1)[0].encode() in painted]


TEXT_RUN = re.compile(r"BT ([\d.]+) ([\d.]+) Td \((.*?)\)' ET")
SEGMENT = re.compile(r'([\d.]+) ([\d.]+) m ([\d.]+) ([\d.]+) l S')
# Property-grid geometry, in points from the page's left text margin (measured on WINDEV 28 dossiers,
# A4 landscape): three label columns, each with its checkbox cell at the right end of the column.
GRID_OFFSETS = (0.0, 252.36, 504.72)
GRID_CELL = (226.0, 251.8)


def ticks(content):
    """Check marks: a short down-right stroke followed by a longer up-right one (how the dossier draws ✓)."""
    segments = [tuple(map(float, m)) for m in SEGMENT.findall(content)]
    return [(a, (b + i) / 2) for (a, b, c, e), (f, g, h, i) in zip(segments, segments[1:])
            if abs(c - f) < 0.1 and abs(e - g) < 0.1 and 1 < c - a < 5 and 1 < b - e < 5 and 3 < h - f < 9 and 3 < i - g < 9]


# Labels as printed by an English-language WINDEV. A dossier printed by another UI language uses other
# words: add them here (the coverage summary of extract() shows when nothing was recognised).
CONTROL_TABLE = {'X position', 'Height (mm)'}  # header that starts a table of controls (windows; reports)
KEY_TABLE = {'Unique Key'}              # header that starts an analysis item table with key columns
COLUMN_TABLE = {'Sortable column'}       # header of a table control's column list (anchored on its "Width")
# Table columns that hold words or numbers, even when every cell of a page happens to be empty.
TEXT_COLUMNS = {'X position', 'Y position', 'Width', 'Height', 'Plane', 'Initial state', 'Button type', 'Input type',
                'Caption', 'Type', 'Direction', 'Default value', 'Height (mm)', 'Width (mm)', 'Thick.', 'Line', 'Position',
                'Horz. alignment', 'Vert. alignment'}
COUNT_COLUMN = re.compile(r'^Nb\.')    # "Nb. columns", "Nb. tabs/row": numbers, not checkboxes
TYPE_WORDS = re.compile(r'integer|String|Memo|Boolean|Date|Time|real|Decimal|identifier|key|Currency|Duration')


def checkboxes(content, carry=None):
    """Boolean values drawn as check marks, from a page's raw content stream.

    Returns (properties, rows): window-level properties from the three-column property grid, and per
    row of a table — control tables (CONTROL_TABLE header) and analysis item tables (KEY_TABLE header)
    — its boolean columns. A column holding words in any row is a text column, never a checkbox; in a
    boolean column a check mark means True and an empty cell False. Tables continue across pages
    without repeating their header: pass the same `carry` dict for consecutive pages of one element.
    """
    # Footnote markers ("Table ¹") are not part of a header name.
    runs = [(float(x), float(y), re.sub(r'\s*\xb9$', '', text.replace('\\(', '(').replace('\\)', ')')))
            for x, y, text in TEXT_RUN.findall(content)]
    marks = ticks(content)
    numeric = lambda t: re.fullmatch(r'-?[\d.]+', t) is not None
    if not runs:
        return {}, {}
    # Row labels start at the body margin, indented a little right of the breadcrumb and section titles: the
    # rightmost text start within 10 points of the left edge (titles can outnumber rows on a page).
    words = [x for x, _, t in runs if re.match(r'\w\w', t)]  # code is drawn token by token: skip " ", "(", "+"
    left = min(words or [x for x, _, _ in runs])
    margin = max(x for x in words or [left] if x < left + 10)
    grid = [margin + offset for offset in GRID_OFFSETS]
    kinds = {**dict.fromkeys(CONTROL_TABLE, 'control'), **dict.fromkeys(KEY_TABLE, 'key'), **dict.fromkeys(COLUMN_TABLE, 'column')}
    anchors = sorted({(y, kinds[t]) for x, y, t in runs
                      if t in kinds and not any(abs(ly - y) < 2 and numeric(lt) for lx, ly, lt in runs)}, reverse=True)
    tables = [(anchors[i + 1][0] if i + 1 < len(anchors) else -1, y, kind, None) for i, (y, kind) in enumerate(anchors)]
    if carry is not None and carry.get('headers'):
        # Rows above the first header of this page continue the previous page's table.
        top = max(y for _, y, _ in runs) + 1
        tables.insert(0, (anchors[0][0] if anchors else -1, top, carry['kind'], carry['headers']))
    in_table = lambda y: any(low < y <= high for low, high, _, _ in tables)
    properties = {}
    for x, y, label in runs:
        if not any(abs(x - column) < 0.5 for column in grid) or in_table(y) or re.fullmatch(r'\w+_\w+', label):
            continue
        if ':' in label or label.startswith('Part ') or re.search(r'\d+/\d+/\d+', label):
            continue  # headings ("Number of elements in window: 18"), breadcrumbs, dates
        # A checkbox property has nothing else on its row within its column (no value text).
        if any(x < lx < x + GRID_CELL[1] and abs(ly - y) < 3 for lx, ly, _ in runs):
            continue
        cell = (x + GRID_CELL[0], x + GRID_CELL[1])
        properties[label] = any(cell[0] <= tx <= cell[1] and -4 <= ty - y <= 10 for tx, ty in marks)
    # A page with no check mark in any grid cell has no checkbox grid (image pages, section openers).
    if not any(any(x + GRID_CELL[0] <= tx <= x + GRID_CELL[1] for x in grid) for tx, _ in marks):
        properties = {}
    rows = {}
    for floor, header_y, kind, carried in tables:
        headers = carried or sorted((x, t) for x, y, t in runs if abs(y - header_y) < 0.5 and x > margin + 50)
        anchor_words = {'control': CONTROL_TABLE, 'key': KEY_TABLE, 'column': {'Width'}}[kind]
        anchor_x = next((x for x, t in headers if t in anchor_words), None)
        if anchor_x is None:
            continue  # the header word sits in the label column: a property, not a table
        if carry is not None:
            carry.update(headers=headers, kind=kind)
        # Word values are centred under their header: a column spans midpoint to midpoint.
        xs = [x for x, _ in headers]
        columns = [(x, (xs[i - 1] + x) / 2 if i else x - 20, (x + xs[i + 1]) / 2 if i + 1 < len(xs) else x + 40, t)
                   for i, (x, t) in enumerate(headers)]
        candidates = []
        for x, y, name in runs:
            if abs(x - margin) >= 0.5 or not (floor < y < header_y + 1) or not re.fullmatch(r'[A-Za-z_][\w$]*', name):
                continue
            same_row = [(lx, lt) for lx, ly, lt in runs if abs(ly - y) < 2 and lx > x + 1]
            if any(lx < x + 100 for lx, _ in same_row):
                continue  # code is drawn token by token ("IF", " ", "Timer"…); table values start far right
            if kind == 'control' and sum(1 for lx, lt in same_row if anchor_x - 20 < lx < anchor_x + 150 and numeric(lt)) < 2:
                continue  # not a control row: detail keys ("Opacity 100") have no X and Y coordinates
            if kind == 'column' and not any(abs(lx - anchor_x) < 30 and numeric(lt) for lx, lt in same_row):
                continue  # a column row has its width under "Width"
            if kind == 'key' and not any(TYPE_WORDS.search(lt) for _, lt in same_row):
                continue
            candidates.append((y, name))
        # Numbers are right-aligned past their header, so only words mark a text column.
        text_columns = TEXT_COLUMNS | {t for _, left, right, t in columns for y, _ in candidates
                                       if any(left <= lx < right and abs(ly - y) < 2 and not numeric(lt) for lx, ly, lt in runs)}
        for y, name in candidates:
            # A check mark is drawn just right of its column header's x, centred on its row (lower when the row wraps).
            values = {t: any(-3 <= tx - hx <= 8 and -4 <= ty - y <= 7 for tx, ty in marks)
                      for hx, _, right, t in columns if t not in text_columns and not COUNT_COLUMN.match(t)
                      and (kind != 'key' or right > anchor_x)}  # analysis: only the key columns
            if values:
                rows[name] = values
    return properties, rows


def split_header(text):
    """('3', ['WINDEV window', 'WIN_X', 'Information on controls'], body) for one page."""
    lines = (text or '').split('\n')
    match = HEADER.match(lines[0].strip()) if lines else None
    if not match:
        return None, [], lines
    # Breadcrumb parts are separated by a \x9b glyph (two spaces in some extractions).
    parts = [p.strip() for p in re.split(r'\x9b|\s{2,}', match[2]) if p.strip()]
    # Second line is "<date> <page><project>": drop it.
    return match[1], parts, lines[2:]


def strip_language(value):
    """'PT: Cancelar' -> {'PT': 'Cancelar'}; plain values stay strings."""
    match = re.match(r'^([A-Z]{2}): (.*)$', value)
    return {match[1]: match[2]} if match else value


def parse_details(lines):
    """Per-control detail blocks: 'Button : BTN_X' followed by 'Key Value' lines."""
    controls, current = {}, None
    for line in lines:
        line = line.strip()
        match = DETAIL.match(line)
        if match and not line.startswith(('Window :', 'Supercontrol :')):
            path = match[2]
            current = controls.setdefault(path.rsplit('.', 1)[-1], {'kind': match[1], 'raw': []})
            if '.' in path:
                current['path'] = path
            if match[3]:
                current['column_index'] = int(match[3])
            continue
        if line.startswith(('Window :', 'Supercontrol :')):
            current = None
            continue
        if current is None or not line:
            continue
        current['raw'].append(line)
        for key, field in FIELDS.items():
            # Longer keys sharing the prefix ("Image handling menu") are other properties.
            if line.startswith(key + ' ') and field not in current and not any(
                    other != key and other.startswith(key + ' ') and line.startswith(other) for other in LONGER):
                value = line[len(key) + 1:].strip()
                if field in ('tab_order', 'input_size') and value.isdigit():
                    value = int(value)
                current[field] = strip_language(value) if isinstance(value, str) else value
    return controls


ITEM_TYPE = (r'Automatic identifier \(\d+ bytes\)|(?:Unsigned |Signed )?\d+-byte (?:integer|real)|Unicode String|String|'
             r'Text Memo|Binary Memo|Image Memo|Boolean|Date and Time \([^)]*\)|Date \([^)]*\)|Time \([^)]*\)|'
             r'Duration(?: \([^)]*\))?|Currency|Decimal|Numeric|Composite key(?:: [\w+$]+)?|Character|Password')
ITEM = re.compile(rf'^([A-Za-z_][\w$]*) (.*?) ?({ITEM_TYPE})(?: (\d+))?(?: (.*))?$')


def parse_items(lines):
    """Analysis file items: name, caption, type (as WINDEV names it), size, default value."""
    items, previous = [], None
    lines = [line.strip() for line in lines]
    # A long type wraps: "… Date and Time" + "(yyyymmddhhmmssccc)".
    for i in range(len(lines) - 1):
        if lines[i + 1].startswith('(') and re.search(r'(?:Date|Time|Duration|Automatic identifier)$', lines[i]):
            lines[i], lines[i + 1] = f'{lines[i]} {lines[i + 1]}', ''
    for line in lines:
        match = ITEM.match(line)
        if match and not line.startswith(('Name on disk', 'Caption Type')):
            sized = match[3] in ('String', 'Unicode String', 'Character', 'Password') or match[3].startswith('Composite key')
            number = int(match[4]) if match[4] else None
            # Only strings have a size; after other types the number is the default value.
            default = (match[5] or '').strip() or (None if sized or number is None else str(number))
            kind, _, components = match[3].partition(': ')
            previous = {'name': match[1], 'caption': match[2].strip(), 'type': kind,
                        'size': number if sized else None, 'default': default}
            if components:
                previous['components'] = components.split('+')
            items.append(previous)
        elif previous and re.fullmatch(r'-?\d+(?:\.\d+)?', line) and previous['default'] is None:
            previous['default'] = line  # the default value wraps onto its own line
    return items


def parse_rows(lines, report=False):
    """Control table rows: position, size, state, input type (windows) or type and bound item (reports), and table
    column rows ("COL_Codigo" then "80 Active Right Center Numeric": width, state, alignments, input type)."""
    rows, previous, previous_name = {}, None, None
    for line in lines:
        line = line.strip()
        if report:
            match = REPORT_ROW.match(line)
            if match:
                previous = rows[match[1]] = {'kind': match[2], 'x_mm': float(match[3]), 'y_mm': float(match[4]),
                                             'height_mm': float(match[5]), 'width_mm': float(match[6]),
                                             'row': (match[7] or '').strip()}
            elif previous and line.startswith('Item '):
                previous['item'] = line[5:].strip()
            continue
        column = COLUMN_ROW.match(line)
        if column and previous_name:
            rows[previous_name] = {'width': int(column[1]), 'state': column[2], 'h_align': column[3],
                                   'v_align': column[4], 'input_type': column[5]}
            previous_name = None
            continue
        previous_name = line if re.fullmatch(r'COL_\w+|[A-Za-z_]\w*', line) else None
        match = WINDOW_ROW.match(line)
        if match:
            rest = (match[7] or '').split()
            row = {'x': int(match[2]), 'y': int(match[3]), 'width': int(match[4]), 'height': int(match[5]),
                   'row': ' '.join(rest)}
            state = next((t for t in rest if t in STATES), None)
            if state:
                row['state'] = 'Read-only' if state.startswith('Read-on') else state
            kind = next((t for t in rest if t in INPUT_TYPES), None)
            if kind:
                row['input_type'] = kind
            if rest and rest[-1] in BUTTON_TYPES:
                row['button_type'] = rest[-1]  # last column of a button's row: "Active Validate"
            rows[match[1]] = row
    return rows


def parse_sql(lines):
    sql, inside = [], False
    for line in lines:
        if line.startswith('SQL code of '):
            inside = True
            continue
        if inside:
            sql.append(line.rstrip())
    return '\n'.join(sql).strip()


def parse_query(lines):
    text = '\n'.join(lines)
    params = re.findall(r'^(Param\w+)\s*$', text, re.M)
    conditions = re.findall(r'^(.+ is .+? (Param\w+))\s+\2\s*$', text, re.M)
    return {'parameters': sorted(set(params)), 'conditions': [c[0] for c in conditions]}


def collect(pages):
    """pages: iterable of page texts. Returns {kind: {element: {...}}}."""
    elements = {}
    for text in pages:
        part, header, body = split_header(text)
        if not part or not header:
            continue
        # Part overview pages ("Part 1  Project") carry project-wide facts such as the first window.
        kind, element = header[0], header[1] if len(header) > 1 else '_general'
        section = header[2] if len(header) > 2 else ''
        item = elements.setdefault(kind, {}).setdefault(element, {'sections': {}, 'lines': []})
        if kind == 'Analysis' and section == 'Files and items' and len(header) > 3:
            # One analysis holds many files: keep each file's pages apart.
            item.setdefault('file_lines', {}).setdefault(header[3], []).extend(body)
        item['sections'].setdefault(section, []).extend(body)
        item['lines'].extend(body)  # page order: a section can start mid-page under the previous header
    for kind, items in elements.items():
        for element, item in items.items():
            sections = item.pop('sections')  # kept only for parsing: `lines` holds the same text in page order
            lines = item['lines']
            general = sections.get('General information', [])
            for line in general:
                for key, field in (('Title', 'title'), ('Window type', 'window_type'), ('Query type', 'query_type'),
                                   ('Opening mode (Desktop)', 'opening_mode'), ('Close icon', 'close_icon')):
                    if line.startswith(key + ' ') and field not in item:
                        item[field] = strip_language(line[len(key) + 1:].strip())
                size = re.match(r'X position (-?\d+) Y position (-?\d+) Width (\d+) Height (\d+)$', line)
                if size and kind == 'WINDEV window' and 'size' not in item:
                    item['size'] = {'x': int(size[1]), 'y': int(size[2]), 'width': int(size[3]), 'height': int(size[4])}
            if 'file_lines' in item:
                item['files'] = {}
                for name, file_lines in item.pop('file_lines').items():
                    description = next((l.split(': ', 1)[1] for l in file_lines if re.match(r'^[A-Z]{2}: .+', l)), None)
                    parsed = parse_items(file_lines)
                    if parsed:  # the section's overview page lists no items
                        item['files'][name] = {'description': description, 'items': parsed}
            # Page order matters: a section can start mid-page under the previous header, and a
            # control's "Item" line must follow its own row. Stop where the code listing starts.
            control_lines = lines[:lines.index('Code')] if 'Code' in lines else lines
            controls = parse_details(control_lines)
            for name, row in parse_rows(control_lines, report=(kind == 'Report')).items():
                target = controls.setdefault(name, {'kind': row.get('kind'), 'raw': []})
                for key, value in row.items():
                    target.setdefault(key, value)
            if controls:
                item['controls'] = controls
            if kind == 'Report':
                start = next((i for i, line in enumerate(lines) if line.startswith('Physical report name')), 0)
                for line in lines[start:]:
                    for key, field in (('Type', 'report_type'), ('Data source type', 'data_source'),
                                       ('Page format', 'page_format')):
                        if line.startswith(key + ' ') and field not in item:
                            item[field] = line[len(key) + 1:].strip()
                margins = dict(re.findall(r'(Top|Bottom|Left|Right) margin \(mm\) ([\d.]+)', '\n'.join(lines)))
                if margins:
                    item['margins_mm'] = {side.lower(): float(value) for side, value in margins.items()}
                # "Details of <Calculation> controls": "COUNTER Counter Numeric" (type, then mask);
                # "Details of <Preset> controls": "NUMNBPAGES [PAGENUM]/[NBPAGES]".
                field = None
                for line in control_lines:
                    heading = re.match(r'Details of <(\w+)> controls', line)
                    if heading:
                        field = {'Calculation': 'calculation', 'Preset': 'preset'}.get(heading[1])
                        continue
                    name, _, rest = line.partition(' ')
                    if field and name in controls and rest.strip():
                        controls[name][field] = rest.strip()
            if kind == 'Query':
                item['sql'] = parse_sql(item['lines'])
                item.update(parse_query(sections.get('Information on the result', []) +
                                        sections.get('Additional information', [])))
    return elements


def extract(pdf, out, images=True):
    from pypdf import PdfReader
    reader = PdfReader(str(pdf))
    texts = [page.extract_text() or '' for page in reader.pages]
    elements = collect(texts)
    carries = {}
    for page, text in zip(reader.pages, texts):
        part, header, _ = split_header(text)
        if not part or len(header) < 2 or header[0] not in elements or header[1] not in elements[header[0]]:
            continue
        if len(header) > 2 and 'code' in header[-1].lower():
            continue  # code listings ("Code", "Control code") hold no checkboxes
        contents = page.get_contents()
        # A table may continue on the next page of the same element (analysis: of the same file), even when
        # that page starts a new section heading.
        carry = carries.setdefault(tuple(header[:4] if header[0] == 'Analysis' else header[:2]), {})
        properties, controls = checkboxes(contents.get_data().decode('latin1') if contents is not None else '', carry)
        item = elements[header[0]][header[1]]
        if properties and header[0] == 'WINDEV window':  # reports and queries have no property grid
            item.setdefault('flags', {}).update(properties)
        if header[0] == 'Analysis':
            # Item key flags belong to the file whose pages these are.
            if len(header) > 3:
                item.setdefault('item_flags', {}).setdefault(header[3], {}).update(controls)
            continue
        for name, values in controls.items():
            target = item.setdefault('controls', {}).setdefault(name, {'kind': None, 'raw': []})
            target.setdefault('flags', {}).update(values)
    out.mkdir(parents=True, exist_ok=True)
    if images:
        for number, text in enumerate(texts):
            part, header, _ = split_header(text)
            if part and len(header) > 2 and header[2] == 'Image' and header[0] in ('WINDEV window', 'Report', 'Query'):
                largest = max(drawn_images(reader.pages[number]), key=lambda image: len(image.data), default=None)
                if largest is not None:
                    target = out / 'images' / f'{header[1]}{Path(largest.name).suffix or ".png"}'
                    target.parent.mkdir(exist_ok=True)
                    target.write_bytes(largest.data)
                    elements[header[0]][header[1]]['image_file'] = str(target.relative_to(out))
    for analysis in elements.get('Analysis', {}).values():
        for file, flags in analysis.pop('item_flags', {}).items():
            for entry in analysis.get('files', {}).get(file, {}).get('items', []):
                if entry['name'] in flags:
                    entry['keys'] = flags[entry['name']]
    for window in elements.get('WINDEV window', {}).values():
        controls = window.get('controls', {})
        for name in [n for n, c in controls.items() if not c.get('kind')]:
            # Control tables cut long names (31 characters): merge into the full name from the detail pages.
            full = [n for n, c in controls.items() if c.get('kind') and n != name and n.split('.')[-1].startswith(name)]
            if len(full) == 1:
                truncated = controls.pop(name)
                controls[full[0]].setdefault('flags', {}).update(truncated.get('flags', {}))
                controls[full[0]]['raw'] = controls[full[0]].get('raw', []) + truncated.get('raw', [])
    for kind, items in elements.items():
        folder = out / re.sub(r'\W+', '-', kind.lower()).strip('-')
        folder.mkdir(exist_ok=True)
        for element, item in items.items():
            # The analysis is named by its Windows path ("C:\\My Projects\\App.ana\\App.wda"): keep the file name.
            stem = re.split(r'[\\/]', element)[-1] if element != '_general' else element
            if stem != element:
                item.setdefault('path', element)
            stem = re.sub(r'[:*?"<>|]', '_', stem)
            (folder / f'{stem}.json').write_text(json.dumps(item, indent=1, ensure_ascii=False), encoding='utf-8')
    summary = {kind: len(items) for kind, items in elements.items()}
    coverage = parsed_coverage(elements)
    (out / 'index.json').write_text(json.dumps({'pages': len(texts), 'images': images, 'elements': summary, 'coverage': coverage},
                                               indent=2), encoding='utf-8')
    for warning in coverage['warnings']:
        print(f'warning: {warning}', file=sys.stderr)
    return {'elements': summary, 'coverage': coverage}


def parsed_coverage(elements):
    """How much of each kind the parser recognised, so a dossier with another layout or UI language
    fails loudly instead of yielding silently empty fields."""
    windows = {k: v for k, v in elements.get('WINDEV window', {}).items() if k != '_general'}
    controls = [c for w in windows.values() for c in w.get('controls', {}).values() if c.get('kind')]
    items = [e for a in elements.get('Analysis', {}).values() for f in a.get('files', {}).values() for e in f['items']]
    queries = {k: v for k, v in elements.get('Query', {}).items() if k != '_general'}
    counts = {
        'windows_with_flags': f"{sum(1 for w in windows.values() if w.get('flags'))}/{len(windows)}",
        'controls_with_caption': f"{sum(1 for c in controls if c.get('caption') or c.get('title'))}/{len(controls)}",
        'controls_with_flags': f"{sum(1 for c in controls if c.get('flags'))}/{len(controls)}",
        'analysis_items_with_keys': f"{sum(1 for e in items if 'keys' in e)}/{len(items)}",
        'queries_with_sql': f"{sum(1 for q in queries.values() if q.get('sql'))}/{len(queries)}",
    }
    reports = {k: v for k, v in elements.get('Report', {}).items() if k != '_general'}
    # Not a parsing gap: the dossier does not print a report's embedded query. It needs an export.
    counts['reports_with_embedded_query'] = sum(1 for r in reports.values() if r.get('data_source') == 'Embedded query')
    warnings = []
    for name, value in counts.items():
        if not isinstance(value, str):
            continue
        found, total = map(int, value.split('/'))
        if total and found < total / 2:
            warnings.append(f'{name} {value}: layout or labels not recognised (see CONTROL_TABLE, KEY_TABLE, '
                            'GRID_OFFSETS in dossier_extract.py); treat the missing fields as not extracted, not as false')
    return {**counts, 'warnings': warnings}


