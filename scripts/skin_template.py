#!/usr/bin/env python3
"""A WINDEV skin template as the new UI's style sheet: every style's font and colour as CSS, its images as PNG.

Where the skin comes from: a control's `style` ("140 iStyle.BTN_Simple") names the template it was designed with, but
the application may change template at run time (`ChangeSkinTemplate(AllComponents, "<file>.wdy")`, often from a
folder delivered beside the executable, e.g. `<exe dir>/Estilos/<template>/`): then EVERY control is drawn with the
style of the same name in that template, whatever template its designer used. Search the project's code for
ChangeSkinTemplate before choosing the template, and read the template from the DELIVERED program folder when the
project folder does not hold it (a project folder usually keeps only the few images some windows name directly).

  python3 scripts/skin_template.py "<exe dir>/Estilos/140 iStyle" --css src/ui/skin/template.generated.css \\
      --images public/skin/template [--strips strips.json]

Output:
- CSS: one rule per style, `[data-wd-style="<style>"]`, with the font of the style's first font record (face, pixel
  size from the LOGFONT height, weight, italic) and its text colour. The UI sets `data-wd-style` on each control's
  root element (the part of the style name after the template's dot). Rules are emitted in style-name order with
  equal specificity: put the project's measured overrides AFTER this file.
- Images: every image a style names, magenta (#ff00ff, the templates' transparent colour) made transparent; with
  `--strips`, the state strips cut one PNG per state (`{"iStyle_Btn_Std.png": [80, 24, 5], …}`: state width, state
  height or null, number of states), since the state count is not in the decoded style sheet: measure it on the image.
- `<css>.json`: the decoded styles (fonts, frames, images) for review.

What is NOT in the style sheet and must be measured on the running application or its screenshots: the 9-slice
margins of the images, which state is hover / pressed / focused, and any font the application substitutes (one
project drew its static captions in Segoe UI 12 px where the sheet said Trebuchet MS 11 px). Requires Pillow for
images (python3 -m pip install pillow).
"""
import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from windev_decode import packed_blocks, skin_styles  # noqa: E402


def decoded_styles(folder):
    """{style: {fonts, frames, images}} of a template folder: the `.sty` file (plain PCS container), else the packed
    blocks of the `.wdy` file."""
    for sty in sorted(folder.glob('*.sty')):
        styles = skin_styles(sty.read_bytes())
        if styles:
            return styles
    for wdy in sorted(folder.glob('*.wdy')):
        for _, _, block in packed_blocks(wdy.read_bytes()):
            styles = skin_styles(block)
            if styles:
                return styles
    raise SystemExit(f'{folder}: no style sheet decoded (.sty / .wdy)')


def substitution(text):
    """`PREFIX:FACE SIZEpx=FACE SIZEpx` (e.g. `LIB_:Trebuchet MS 11px=Segoe UI 12px`) → (prefix, (face, size), (face, size))."""
    prefix, _, rule = text.partition(':')
    source, _, target = rule.partition('=')
    parse = lambda part: (part.rsplit(' ', 1)[0].strip(), int(part.rsplit(' ', 1)[1].strip().removesuffix('px')))
    return prefix, parse(source), parse(target)


def css_of(styles, substitutions=()):
    lines = ['/* Generated by scripts/skin_template.py from the skin template\'s style sheet: one rule per style,',
             '   first font record (face, LOGFONT height in px, weight) and text colour. Do not edit: override after it. */']
    for name in sorted(styles):
        fonts = styles[name].get('fonts') or []
        if not fonts:
            continue
        font = fonts[0]
        size = -font['height'] if font.get('height', 0) < 0 else None
        face = font['face']
        # a font the running application draws differently than the sheet says (measured on its screenshots)
        for prefix, (old_face, old_size), (new_face, new_size) in substitutions:
            if name.startswith(prefix) and face == old_face and size == old_size:
                face, size = new_face, new_size
        decl = []
        if size:
            style = 'italic ' if font.get('italic') else ''
            decl.append(f'font: {style}{font.get("weight", 400)} {size}px "{face}", sans-serif')
        if font.get('colour'):
            decl.append(f'color: {font["colour"]}')
        if font.get('underline'):
            decl.append('text-decoration: underline')
        if decl:
            selector = name.replace('\\', '\\\\').replace('"', '\\"')
            lines.append(f'[data-wd-style="{selector}"] {{ {"; ".join(decl)}; }}')
    return '\n'.join(lines) + '\n'


def transparent(image):
    image = image.convert('RGBA')
    pixels = image.load()
    for y in range(image.height):
        for x in range(image.width):
            if pixels[x, y][:3] == (255, 0, 255):
                pixels[x, y] = (0, 0, 0, 0)
    return image


def export_images(folder, styles, out, strips):
    from PIL import Image
    out.mkdir(parents=True, exist_ok=True)
    names = sorted({image for style in styles.values() for image in style.get('images', [])})
    written = 0
    for name in names:
        source = folder / name
        if not source.exists():
            continue
        stem = Path(name).stem
        if source.suffix.lower() == '.svg':  # vector images are used as they are
            (out / source.name).write_bytes(source.read_bytes())
            written += 1
            continue
        image = transparent(Image.open(source))
        image.save(out / f'{stem}.png')
        written += 1
        if name in strips:
            width, height, states = strips[name]
            for state in range(states):
                image.crop((state * width, 0, (state + 1) * width, height or image.height)).save(out / f'{stem}.{state}.png')
    return written, len(names)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('template', type=Path, help='the skin template folder (.sty / .wdy and its images)')
    parser.add_argument('--css', type=Path, required=True)
    parser.add_argument('--images', type=Path, help='folder for the PNG images (default: none written)')
    parser.add_argument('--strips', type=Path, help='JSON {image: [state width, state height|null, states]}')
    parser.add_argument('--substitute', action='append', default=[], type=substitution,
                        help='a measured font substitution, e.g. "LIB_:Trebuchet MS 11px=Segoe UI 12px" (repeatable)')
    args = parser.parse_args()
    styles = decoded_styles(args.template)
    args.css.parent.mkdir(parents=True, exist_ok=True)
    args.css.write_text(css_of(styles, args.substitute), encoding='utf-8')
    args.css.with_suffix('.json').write_text(json.dumps(styles, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
    message = f'{len(styles)} styles -> {args.css}'
    if args.images:
        strips = json.loads(args.strips.read_text(encoding='utf-8')) if args.strips else {}
        written, named = export_images(args.template, styles, args.images, strips)
        message += f'; {written} of {named} named images -> {args.images}'
    print(message)


if __name__ == '__main__':
    main()
